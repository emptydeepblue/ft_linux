#!/bin/bash
# System 04 — GRUB (LFS 12.4 §10.4), BIOS/MBR (i386-pc).
# Installs GRUB in the MBR of the disk that holds /boot and writes
# /boot/grub/grub.cfg for the evaluation VM (disk = /dev/sda there).
# Run INSIDE the chroot as root, after 03_kernel.sh.
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"
KERNEL="vmlinuz-$KERNEL_RELEASE"

echo ">>> GRUB"

if ! mountpoint -q /boot; then
    echo "ERROR: /boot is not mounted." >&2
    exit 1
fi
[ -f "/boot/$KERNEL" ] || { echo "ERROR: /boot/$KERNEL missing, run 03_kernel.sh." >&2; exit 1; }

# Disk = parent of the partition mounted on /boot (e.g. /dev/loop2p1 ->
# /dev/loop2 while building on an image, /dev/sdb1 -> /dev/sdb on a disk).
BOOT_PART="$(findmnt -no SOURCE /boot)"
DISK="/dev/$(lsblk -no PKNAME "$BOOT_PART" | head -n1)"
if [ ! -b "$DISK" ] || [ "$DISK" = "/dev/" ]; then
    echo "ERROR: cannot find the disk of $BOOT_PART." >&2
    exit 1
fi
echo "  /boot is $BOOT_PART -> installing GRUB on $DISK"

grub-install --target=i386-pc            \
             --boot-directory=/boot      \
             --modules="part_msdos ext2" \
             "$DISK"

# /boot is its own partition (p1), so paths are relative to it: /vmlinuz-...
# root= uses the device name inside the VM (SATA port 0 -> /dev/sda).
# net.ifnames=0 keeps the classic eth0 name (see /etc/sysconfig/ifconfig.eth0).
cat > /boot/grub/grub.cfg << EOF
# Begin /boot/grub/grub.cfg
# Generated by scripts/03_system/04_grub.sh
set default=0
set timeout=5

insmod part_msdos
insmod ext2
set root=(hd0,msdos1)

menuentry "ft_linux - Linux $KERNEL_RELEASE" {
    linux /$KERNEL root=$VM_ROOT_DEV ro net.ifnames=0
}

menuentry "ft_linux - Linux $KERNEL_RELEASE (single user)" {
    linux /$KERNEL root=$VM_ROOT_DEV ro net.ifnames=0 single
}
# End /boot/grub/grub.cfg
EOF

echo "<<< GRUB done ($DISK, /boot/grub/grub.cfg -> $KERNEL, root=$VM_ROOT_DEV)"
