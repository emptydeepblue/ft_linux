#!/bin/bash
# System 02 — /etc configuration (LFS 12.4 §9.5–9.9, §10.2, §11.1)
# hostname, hosts, network (DHCP on eth0), inittab, clock, console, profile,
# inputrc, shells, fstab, modprobe, release files. Values from ft_linux.conf.
# Idempotent: safe to re-run. Run INSIDE the chroot as root.
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"

echo ">>> System configuration (hostname: $FT_HOSTNAME)"

# ── Network (§9.5) ───────────────────────────────────────────────────────────
echo "$FT_HOSTNAME" > /etc/hostname

cat > /etc/hosts << EOF
# Begin /etc/hosts

127.0.0.1 localhost.localdomain localhost
127.0.1.1 $FT_HOSTNAME.localdomain $FT_HOSTNAME
::1       localhost ip6-localhost ip6-loopback
ff02::1   ip6-allnodes
ff02::2   ip6-allrouters

# End /etc/hosts
EOF

# DHCP on eth0 (VirtualBox NAT). The kernel is booted with net.ifnames=0, so
# the first NIC is always eth0. SERVICE=dhcpcd needs dhcpcd + its BLFS
# service script (installed by the network step, plan point 7).
install -d /etc/sysconfig
cat > /etc/sysconfig/ifconfig.eth0 << "EOF"
ONBOOT=yes
IFACE=eth0
SERVICE=dhcpcd
DHCP_START="-b -q"
DHCP_STOP="-k"
EOF

# Fallback resolvers; dhcpcd overwrites this with the DHCP-provided ones.
cat > /etc/resolv.conf << "EOF"
# Begin /etc/resolv.conf

nameserver 1.1.1.1
nameserver 8.8.8.8

# End /etc/resolv.conf
EOF

# ── Init (§9.6) ──────────────────────────────────────────────────────────────
cat > /etc/inittab << "EOF"
# Begin /etc/inittab

id:3:initdefault:

si::sysinit:/etc/rc.d/init.d/rc S

l0:0:wait:/etc/rc.d/init.d/rc 0
l1:S1:wait:/etc/rc.d/init.d/rc 1
l2:2:wait:/etc/rc.d/init.d/rc 2
l3:3:wait:/etc/rc.d/init.d/rc 3
l4:4:wait:/etc/rc.d/init.d/rc 4
l5:5:wait:/etc/rc.d/init.d/rc 5
l6:6:wait:/etc/rc.d/init.d/rc 6

ca:12345:ctrlaltdel:/sbin/shutdown -t1 -a -r now

su:S06:once:/sbin/sulogin
s1:1:respawn:/sbin/sulogin

1:2345:respawn:/sbin/agetty --noclear tty1 9600
2:2345:respawn:/sbin/agetty tty2 9600
3:2345:respawn:/sbin/agetty tty3 9600
4:2345:respawn:/sbin/agetty tty4 9600
5:2345:respawn:/sbin/agetty tty5 9600
6:2345:respawn:/sbin/agetty tty6 9600

# End /etc/inittab
EOF

cat > /etc/sysconfig/clock << "EOF"
# Begin /etc/sysconfig/clock

UTC=1

# Set this to any options you might need to give to hwclock,
# such as machine hardware clock type for Alphas.
CLOCKPARAMS=

# End /etc/sysconfig/clock
EOF

cat > /etc/sysconfig/console << "EOF"
# Begin /etc/sysconfig/console

KEYMAP="us"

# End /etc/sysconfig/console
EOF

# ── Shell environment (§9.7–9.9) ─────────────────────────────────────────────
# C.UTF-8 is always available (generated by the Glibc step).
cat > /etc/profile << "EOF"
# Begin /etc/profile

export LANG=C.UTF-8
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin

if [ "$(id -u)" -eq 0 ]; then
    PS1='\u@\h:\w# '
else
    PS1='\u@\h:\w$ '
fi
export PS1

# End /etc/profile
EOF

cat > /etc/inputrc << "EOF"
# Begin /etc/inputrc
# Modified by Chris Lynn <roryo@roryo.dynup.net>

# Allow the command prompt to wrap to the next line
set horizontal-scroll-mode Off

# Enable 8-bit input
set meta-flag On
set input-meta On

# Turns off 8th bit stripping
set convert-meta Off

# Keep the 8th bit for display
set output-meta On

# none, visible or audible
set bell-style none

# All of the following map the escape sequence of the value
# contained in the 1st argument to the readline specific functions
"\eOd": backward-word
"\eOc": forward-word

# for linux console
"\e[1~": beginning-of-line
"\e[4~": end-of-line
"\e[5~": beginning-of-history
"\e[6~": end-of-history
"\e[3~": delete-char
"\e[2~": quoted-insert

# for xterm
"\eOH": beginning-of-line
"\eOF": end-of-line

# for Konsole
"\e[H": beginning-of-line
"\e[F": end-of-line

# End /etc/inputrc
EOF

cat > /etc/shells << "EOF"
# Begin /etc/shells

/bin/sh
/bin/bash

# End /etc/shells
EOF

# ── fstab (§10.2) — device names as seen inside the evaluation VM ───────────
cat > /etc/fstab << EOF
# Begin /etc/fstab

# file system  mount-point    type     options             dump  fsck
#                                                                order

$VM_ROOT_DEV      /              ext4     defaults            1     1
$VM_BOOT_DEV      /boot          ext4     defaults            1     2
$VM_SWAP_DEV      swap           swap     pri=1               0     0
proc           /proc          proc     nosuid,noexec,nodev 0     0
sysfs          /sys           sysfs    nosuid,noexec,nodev 0     0
devpts         /dev/pts       devpts   gid=5,mode=620      0     0
tmpfs          /run           tmpfs    defaults            0     0
devtmpfs       /dev           devtmpfs mode=0755,nosuid    0     0
tmpfs          /dev/shm       tmpfs    nosuid,nodev        0     0
cgroup2        /sys/fs/cgroup cgroup2  nosuid,noexec,nodev 0     0

# End /etc/fstab
EOF

# ── USB module ordering (§10.3.2) ────────────────────────────────────────────
install -v -m755 -d /etc/modprobe.d
cat > /etc/modprobe.d/usb.conf << "EOF"
# Begin /etc/modprobe.d/usb.conf

install ohci_hcd /sbin/modprobe ehci_hcd ; /sbin/modprobe -i ohci_hcd ; true
install uhci_hcd /sbin/modprobe ehci_hcd ; /sbin/modprobe -i uhci_hcd ; true

# End /etc/modprobe.d/usb.conf
EOF

# ── Release files (§11.1) ────────────────────────────────────────────────────
echo "$LFS_VERSION" > /etc/lfs-release

cat > /etc/lsb-release << EOF
DISTRIB_ID="Linux From Scratch"
DISTRIB_RELEASE="$LFS_VERSION"
DISTRIB_CODENAME="$FT_LOGIN"
DISTRIB_DESCRIPTION="ft_linux (Linux From Scratch $LFS_VERSION)"
EOF

cat > /etc/os-release << EOF
NAME="Linux From Scratch"
VERSION="$LFS_VERSION"
ID=lfs
PRETTY_NAME="ft_linux by $FT_LOGIN (LFS $LFS_VERSION SysV)"
VERSION_CODENAME="$FT_LOGIN"
HOME_URL="https://www.linuxfromscratch.org/lfs/"
RELEASE_TYPE="stable"
EOF

echo "<<< System configuration done"
